// Autify Nexus — Gestión de perfil.
const { test, expect } = require('@playwright/test')

test('Cambiar el nombre en Mi perfil actualiza el saludo', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Nombre completo').fill('Ana Pérez')
  await page.getByLabel('Email').fill(`nexus+${Date.now()}@gmail.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Medellin2026')
  await page.getByLabel('Confirmar contraseña').fill('Medellin2026')
  await page.getByRole('button', { name: 'Crear cuenta gratis' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.getByRole('link', { name: 'Editar perfil' }).click()
  await page.getByLabel('Nombre completo').fill('María Gómez')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByTestId('toast')).toContainText('Perfil actualizado')
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Hola, María')
})

test('Descartar cambios devuelve el nombre guardado', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Nombre completo').fill('Ana Pérez')
  await page.getByLabel('Email').fill(`nexus+${Date.now()}@gmail.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Medellin2026')
  await page.getByLabel('Confirmar contraseña').fill('Medellin2026')
  await page.getByRole('button', { name: 'Crear cuenta gratis' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.goto('/profile')
  await expect(page.getByRole('button', { name: 'Descartar cambios' })).toBeDisabled()
  await page.getByLabel('Nombre completo').fill('Otro Nombre')
  await page.getByRole('button', { name: 'Descartar cambios' }).click()
  await expect(page.getByLabel('Nombre completo')).toHaveValue('Ana Pérez')
})

test('Cambiar la contraseña con la actual incorrecta muestra el error', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Nombre completo').fill('Ana Pérez')
  await page.getByLabel('Email').fill(`nexus+${Date.now()}@gmail.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Medellin2026')
  await page.getByLabel('Confirmar contraseña').fill('Medellin2026')
  await page.getByRole('button', { name: 'Crear cuenta gratis' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.goto('/profile')
  await page.getByLabel('Contraseña actual').fill('NoEsLaClave1')
  await page.getByLabel('Contraseña nueva', { exact: true }).fill('ClaveNueva2027')
  await page.getByLabel('Confirmar contraseña nueva').fill('ClaveNueva2027')
  await page.getByRole('button', { name: 'Cambiar contraseña' }).click()
  await expect(page.getByRole('alert')).toContainText('La contraseña actual no es correcta')
})
